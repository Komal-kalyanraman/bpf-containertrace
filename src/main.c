/*
 * main.c – Core daemon entry point
 *
 * Lifecycle:
 *   1. Validate environment (root, BTF present).
 *   2. Load the eBPF skeleton (open → load → attach).
 *   3. Initialise the cgroup resolver (inotify + initial scan).
 *   4. Enter the main poll loop:
 *        a. Drain the BPF ring buffer (BPF events → console).
 *        b. Drain inotify events    (container start/stop).
 *   5. On SIGINT/SIGTERM: clean shutdown.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <unistd.h>
#include <errno.h>
#include <time.h>
#include <sys/stat.h>

#include <bpf/libbpf.h>
#include <bpf/bpf.h>

/* Generated by `bpftool gen skeleton` – included from the build dir. */
#include "containertrace.skel.h"

#include "containertrace_event.h"
#include "cgroup_resolver.h"
#include "logger.h"

#define VERSION "0.1.0"

/* ------------------------------------------------------------------ */
/* Signal handling                                                     */
/* ------------------------------------------------------------------ */

static volatile int g_running = 1;

static void on_signal(int sig)
{
    (void)sig;
    g_running = 0;
}

/* ------------------------------------------------------------------ */
/* libbpf log callback (route libbpf messages through our logger)     */
/* ------------------------------------------------------------------ */

static int libbpf_print(enum libbpf_print_level level,
                         const char *fmt, va_list args)
{
    if (level == LIBBPF_DEBUG)
        return 0;   /* suppress debug noise */
    vfprintf(stderr, fmt, args);
    return 0;
}

/* ------------------------------------------------------------------ */
/* Periodic CPU stats report                                           */
/* ------------------------------------------------------------------ */

#define RESCAN_INTERVAL_S  3   /* re-scan cgroup tree for new containers */
#define STATS_INTERVAL_S   5   /* print per-container CPU stats          */

/*
 * Read the container_cpu_stats BPF map and emit an INFO-level usage line
 * for every tracked container.  Called on a fixed interval so users see
 * activity even when there are no quota violations (unlimited containers).
 */
static void print_stats_report(int stats_map_fd,
                                const struct cgroup_resolver *res)
{
    int n = cgroup_resolver_get_count(res);
    if (n == 0) return;

    LOG_INFO("--- CPU stats (current period) ---");
    for (int i = 0; i < n; i++) {
        const struct ct_container *c = cgroup_resolver_get_container(res, i);
        if (!c) continue;

        struct ct_cpu_stat stat = {0};
        if (bpf_map_lookup_elem(stats_map_fd, &c->cgid, &stat) != 0)
            continue;

        uint64_t used_ms = stat.cpu_ns_used / 1000000ULL;

        if (c->limits.cpu_quota_ns > 0) {
            double pct = 100.0 * (double)stat.cpu_ns_used
                         / (double)c->limits.cpu_quota_ns;
            LOG_INFO("  %-20s  used=%5llums / quota=%5llums  (%.0f%%)%s",
                     c->name,
                     (unsigned long long)used_ms,
                     (unsigned long long)(c->limits.cpu_quota_ns / 1000000ULL),
                     pct,
                     pct > 100.0 ? "  *** OVER QUOTA ***" : "");
        } else {
            LOG_INFO("  %-20s  used=%5llums  (no cpu quota set)",
                     c->name,
                     (unsigned long long)used_ms);
        }
    }
}

/* ------------------------------------------------------------------ */
/* Ring-buffer event handler                                           */
/* ------------------------------------------------------------------ */

static int handle_bpf_event(void *ctx, void *data, size_t data_sz)
{
    if (data_sz < sizeof(struct ct_event))
        return 0;

    const struct ct_event  *e   = data;
    struct cgroup_resolver *res = ctx;

    const struct ct_container *c =
        cgroup_resolver_find_by_cgid(res, e->cgid);
    const char *name = (c && c->name[0]) ? c->name : "<unknown>";

    if (e->event_type == CT_EVENT_VIOLATION) {
        /*
         * Calculate how far over the quota the container went
         * within this CPU period.
         */
        double pct_over = (e->cpu_quota_ns > 0)
            ? (100.0 * ((double)e->cpu_used_ns / e->cpu_quota_ns) - 100.0)
            : 0.0;

        LOG_WARN("[CPU VIOLATION] %-20s  pid=%-6u  comm=%-15s  "
                 "used=%5llums  quota=%5llums  +%.1f%% over",
                 name,
                 e->pid,
                 (const char *)e->comm,
                 (unsigned long long)(e->cpu_used_ns  / 1000000ULL),
                 (unsigned long long)(e->cpu_quota_ns / 1000000ULL),
                 pct_over);
    } else {
        /* Normal tick – only log if debug is enabled. */
        LOG_DEBUG("[CPU TICK]      %-20s  pid=%-6u  comm=%-15s  "
                  "slice=%lluus  period_total=%lluus",
                  name,
                  e->pid,
                  (const char *)e->comm,
                  (unsigned long long)(e->cpu_delta_ns / 1000ULL),
                  (unsigned long long)(e->cpu_used_ns  / 1000ULL));
    }

    return 0;
}

/* ------------------------------------------------------------------ */
/* main                                                                */
/* ------------------------------------------------------------------ */

int main(void)
{
    /* --- Privilege check ------------------------------------------ */
    if (geteuid() != 0) {
        fprintf(stderr, "Error: bpf-containertrace must be run as root.\n");
        return EXIT_FAILURE;
    }

    /* --- Signal handling ------------------------------------------ */
    struct sigaction sa = { .sa_handler = on_signal };
    sigemptyset(&sa.sa_mask);
    sigaction(SIGINT,  &sa, NULL);
    sigaction(SIGTERM, &sa, NULL);

    LOG_INFO("bpf-containertrace v" VERSION " starting...");

    /* --- BTF check ------------------------------------------------- */
    {
        struct stat st;
        if (stat("/sys/kernel/btf/vmlinux", &st) != 0) {
            LOG_ERROR("BTF not found at /sys/kernel/btf/vmlinux. "
                      "Kernel must be built with CONFIG_DEBUG_INFO_BTF=y.");
            return EXIT_FAILURE;
        }
        LOG_INFO("BTF kernel debug info detected (/sys/kernel/btf/vmlinux).");
    }

    /* --- libbpf verbosity ----------------------------------------- */
    libbpf_set_print(libbpf_print);

    /* --- Load BPF skeleton ---------------------------------------- */
    struct containertrace *skel = containertrace__open_and_load();
    if (!skel) {
        LOG_ERROR("Failed to open/load BPF skeleton (errno=%d).", errno);
        return EXIT_FAILURE;
    }

    int err = containertrace__attach(skel);
    if (err) {
        LOG_ERROR("Failed to attach BPF probes (err=%d).", err);
        containertrace__destroy(skel);
        return EXIT_FAILURE;
    }
    LOG_INFO("eBPF probes attached successfully (sched:sched_switch).");

    /* --- Cgroup resolver ------------------------------------------ */
    struct cgroup_resolver *res = cgroup_resolver_init(
        bpf_map__fd(skel->maps.container_limits),
        bpf_map__fd(skel->maps.container_cpu_stats));
    if (!res) {
        LOG_ERROR("Failed to initialise cgroup resolver.");
        containertrace__destroy(skel);
        return EXIT_FAILURE;
    }

    cgroup_resolver_scan(res);
    LOG_INFO("Watching /sys/fs/cgroup/ via inotify (root + rootless Podman).");

    /* --- Ring buffer ---------------------------------------------- */
    struct ring_buffer *rb = ring_buffer__new(
        bpf_map__fd(skel->maps.events),
        handle_bpf_event, res, NULL);
    if (!rb) {
        LOG_ERROR("Failed to create ring buffer consumer.");
        cgroup_resolver_destroy(res);
        containertrace__destroy(skel);
        return EXIT_FAILURE;
    }

    LOG_INFO("Daemon running. Monitoring Podman containers. "
             "Press Ctrl+C to stop.");

    /* Cache the stats map fd for the periodic report. */
    int stats_map_fd = bpf_map__fd(skel->maps.container_cpu_stats);

    /* Timestamps for periodic tasks. */
    struct timespec last_rescan = {0};
    struct timespec last_stats  = {0};

    /* --- Main event loop ------------------------------------------ */
    while (g_running) {
        /* Poll ring buffer with a 100 ms timeout. */
        err = ring_buffer__poll(rb, 100 /* ms */);
        if (err < 0 && err != -EINTR) {
            LOG_ERROR("ring_buffer__poll: %d", err);
            break;
        }

        /* Drain pending inotify events (container start/stop). */
        cgroup_resolver_process_events(res);

        struct timespec now;
        clock_gettime(CLOCK_MONOTONIC, &now);

        /* Periodic rescan: catch containers missed by inotify (e.g. rootless
         * containers whose parent session dir was already being watched when
         * the container started but before we set up its inner watch). */
        if (now.tv_sec - last_rescan.tv_sec >= RESCAN_INTERVAL_S) {
            cgroup_resolver_scan(res);
            last_rescan = now;
        }

        /* Periodic stats: report CPU usage for all tracked containers,
         * including those with no quota (so activity is always visible). */
        if (now.tv_sec - last_stats.tv_sec >= STATS_INTERVAL_S) {
            print_stats_report(stats_map_fd, res);
            last_stats = now;
        }
    }

    /* --- Graceful shutdown ---------------------------------------- */
    LOG_INFO("Shutting down...");
    ring_buffer__free(rb);
    cgroup_resolver_destroy(res);
    containertrace__destroy(skel);
    LOG_INFO("Done.");
    return EXIT_SUCCESS;
}
